def extract_destinations(text: str) -> list[str]:
    """
    从文本中提取目的地关键词。

    采用最长匹配优先策略：先尝试匹配长词，再匹配短词，
    避免「大阪」匹配到「大」这类歧义情况。
    最终结果去重并保留原始顺序（首次出现位置）。

    参数:
        text: 已清洗的攻略正文。

    返回:
        识别到的目的地列表，如 ["京都", "大阪", "日本"]。
    """
    found: list[str] = []
    seen: set[str] = set()
    for dest in _ALL_DESTINATIONS:
        if dest in text and dest not in seen:
            found.append(dest)
            seen.add(dest)
    return found


def extract_categories(text: str) -> list[ArticleCategory]:
    """
    从文本中识别内容分类标签。

    对每个分类（TRANSPORT / HOTEL / FOOD / ATTRACTION / TIPS）统计
    关键词命中次数，命中至少 1 个关键词即认定该分类存在。
    一篇攻略可同时属于多个分类。

    参数:
        text: 已清洗的攻略正文。

    返回:
        命中的分类枚举列表，如 [ArticleCategory.FOOD, ArticleCategory.ATTRACTION]。
    """
    categories: list[ArticleCategory] = []
    for category, keywords in _CATEGORY_KEYWORDS.items():
        if any(kw in text for kw in keywords):
            categories.append(category)
    return categories


def extract_metadata(text: str, title: str = "") -> dict:
    """
    主入口：对文本（含标题）执行完整元数据提取。

    将标题与正文拼接后统一检索，确保标题中出现的目的地
    也能被正确识别（如标题「3天京都行程」中的「京都」）。

    参数:
        text:  已清洗的攻略正文。
        title: 攻略标题（可为空），与正文合并后一起检索。

    返回:
        包含 destinations（list[str]）和 categories（list[ArticleCategory]）的字典。
    """
    combined = f"{title}\n{text}" if title else text
    destinations = extract_destinations(combined)
    categories = extract_categories(combined)
    # 若未能识别任何分类，默认归入 TIPS（通用攻略）
    if not categories:
        categories = [ArticleCategory.TIPS]
    return {
        "destinations": destinations,
        "categories": categories,
    }
